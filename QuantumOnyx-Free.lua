local Dyn = {
        {"^Points Available: ", "可用点数："},
        {"^Melee: ", "近战："},
        {"^Defense: ", "防御："},
        {"^Sword: ", "剑："},
        {"^Gun: ", "枪："},
        {"^Demon Fruit: ", "恶魔果实："},
    }

    local function trim(s)
        return s and (s:gsub("^%s+", ""):gsub("%s+$", "")) or s
    end
    local function tr(raw)
        if type(raw) ~= "string" or raw == "" then return raw end
        if T[raw] then return T[raw] end
        local t2 = T[trim(raw)]
        if t2 then return t2 end
        for i = 1, #Dyn do
            local pre, zh = Dyn[i][1], Dyn[i][2]
            local rest = raw:match(pre .. "(.*)$")
            if rest then return zh .. rest end
        end
        return raw
    end

    local textClasses = { TextLabel = true, TextButton = true, TextBox = true }
    local hooking = setmetatable({}, { __mode = "k" })

    local function hookObject(obj, class)
        local function applyText()
            local ok, cur = pcall(function() return obj.Text end)
            if not ok then return end
            local nt = tr(cur)
            if nt ~= cur then
                pcall(function()
                    obj.Text = nt
                    obj.Font = Enum.Font.SourceSansBold
                end)
            end
        end
        pcall(function()
            obj:GetPropertyChangedSignal("Text"):Connect(function()
                if hooking[obj] then return end
                hooking[obj] = true
                applyText()
                hooking[obj] = false
            end)
        end)
        if class == "TextBox" then
            pcall(function()
                obj:GetPropertyChangedSignal("PlaceholderText"):Connect(function()
                    local cur = obj.PlaceholderText
                    local np = tr(cur)
                    if np ~= cur then obj.PlaceholderText = np end
                end)
            end)
        end
    end

    local hf = hookfunction or (getgenv and getgenv().hookfunction)
    if not hf then
        warn("[QO Translator] 执行器不支持 hookfunction，无法实时汉化。")
        return
    end

    local oldNew
    oldNew = hf(Instance.new, function(class, parent, ...)
        local obj = oldNew(class, parent, ...)
        if textClasses[class] then
            pcall(hookObject, obj, class)
        end
        return obj
    end)
end

local function LoadGameScript()
    local entry = GameScripts[game.GameId]
    if not entry then
        Notify("Quantum Onyx", "当前游戏暂不受支持。", 8)
        warn("[Quantum Onyx] 当前 GameId 没有对应脚本：" .. tostring(game.GameId))
        return
    end

    InstallTranslator()
    Notify("Quantum Onyx", "正在加载 " .. entry.name .. " …", 4)

    local ok, err = pcall(function()
        loadstring(game:HttpGet(entry.url))()
    end)

    if not ok then
        Notify("Quantum Onyx", "加载失败：" .. tostring(err):sub(1, 80), 8)
        warn("[Quantum Onyx] 加载失败：" .. tostring(err))
    end
end

LoadGameScript()
